import { fileURLToPath } from 'node:url';
import fs from 'node:fs';
import express from 'express';
import dotenv from 'dotenv';
dotenv.config({ path: fileURLToPath(new URL('../.env', import.meta.url)) });
process.env.MONGODB_URI = 'mongodb://127.0.0.1:27017/awaaz_dastak_showcase';
process.env.CLIENT_ORIGIN = 'http://127.0.0.1:5327';
process.env.APP_MODE = 'demo';
process.env.NODE_ENV = 'development';
if (!process.env.VAULT_KEY || !process.env.DOCS_KEY) throw new Error('REHEARSAL_ENCRYPTION_KEYS_REQUIRED');
const root = fileURLToPath(new URL('../client/dist/', import.meta.url));
if (!fs.existsSync(root + '/index.html')) throw new Error('BUILD_CLIENT_FIRST');
const [{ createApp }, { connectDB, disconnectDB }] = await Promise.all([import('../server/src/app.js'), import('../server/src/config/db.js')]);
await connectDB(process.env.MONGODB_URI);
const api = createApp();
const frontend = express();
frontend.use((req, res, next) => req.url.startsWith('/api/') ? api(req, res, next) : next());
frontend.use(express.static(root));
frontend.get(/.*/, (_req, res) => res.sendFile(root + '/index.html'));
const server = frontend.listen(5327, '127.0.0.1');
await new Promise((resolve, reject) => { server.once('listening', resolve); server.once('error', reject); });
console.log('Global jury audit: built client and live API on http://127.0.0.1:5327; showcase only; no reset.');
for (const signal of ['SIGINT', 'SIGTERM']) process.once(signal, () => server.close(() => disconnectDB().then(() => process.exit(0))));
