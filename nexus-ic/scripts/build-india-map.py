"""Decode shared TopoJSON state arcs into offline SVG paths and GeoJSON.
Input: data/maps/india-topology.json from the documented public source.
No boundaries are invented; retain the illustrative/non-official UI label.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
data = json.loads((ROOT / 'data/maps/india-topology.json').read_text())
transform = data['transform']
arcs = []
for arc in data['arcs']:
    x = y = 0
    points = []
    for dx, dy in arc:
        x += dx; y += dy
        points.append([x * transform['scale'][0] + transform['translate'][0], y * transform['scale'][1] + transform['translate'][1]])
    arcs.append(points)

def ring(indices):
    result = []
    for index in indices:
        points = arcs[index] if index >= 0 else list(reversed(arcs[~index]))
        result.extend(points if not result else points[1:])
    return result

def project(point):
    return [round(25 + (point[0] - 68) * 18.2, 2), round(20 + (37.2 - point[1]) * 19.3, 2)]

states, features = [], []
for geometry in data['objects']['states']['geometries']:
    groups = [geometry['arcs']] if geometry['type'] == 'Polygon' else geometry['arcs']
    polygons = [[ring(indices) for indices in polygon] for polygon in groups]
    paths = []
    all_points = []
    for polygon in polygons:
        for points in polygon:
            projected = [project(p) for p in points]
            all_points.extend(projected)
            paths.append('M' + 'L'.join(f'{x},{y}' for x, y in projected) + 'Z')
    # Use the largest outer ring's mean as a representative state location,
    # never an invented city or institute coordinate.
    main = max((polygon[0] for polygon in polygons), key=len)
    center = project([sum(p[0] for p in main)/len(main), sum(p[1] for p in main)/len(main)])
    states.append({'name': geometry['id'], 'd': ''.join(paths), 'center': {'x': center[0], 'y': center[1]}})
    features.append({'type': 'Feature', 'properties': {'name': geometry['id']}, 'geometry': {'type': 'MultiPolygon', 'coordinates': polygons}})

target = ROOT / 'client/src/components/maps'
target.mkdir(exist_ok=True)
(target / 'indiaStates.js').write_text('// Generated by scripts/build-india-map.py; see public/maps/SOURCE.md.\nexport const INDIA_STATES = ' + json.dumps(states, separators=(',', ':')) + ';\n', encoding='utf-8')
(ROOT / 'client/public/maps/india-states.geojson').write_text(json.dumps({'type': 'FeatureCollection', 'features': features}, separators=(',', ':')), encoding='utf-8')
print(json.dumps({'statesAndUTs': len(states), 'names': sorted(s['name'] for s in states)}))
