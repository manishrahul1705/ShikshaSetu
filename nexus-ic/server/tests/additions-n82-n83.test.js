import { beforeEach, it, expect } from 'vitest';
import crypto from 'node:crypto';
import User from '../src/modules/auth/User.js';
import Case from '../src/modules/cases/Case.js';
import Query from '../src/modules/queries/models.js';
import AuditEvent from '../src/modules/audit/AuditEvent.js';
import { seedDemoAccounts } from '../src/modules/auth/seed.js';
import * as combined from '../src/modules/additions/n82-combined-request/service.js';
import * as locker from '../src/modules/additions/n83-document-locker/service.js';
let rb, pgrc, institution, c1, c2;
const pid = '1-1000000001';
beforeEach(async () => {
  process.env.DOCS_KEY = crypto.randomBytes(32).toString('hex');
  await seedDemoAccounts();
  rb = await User.findOne({ username: 'rb_officer1' });
  pgrc = await User.findOne({ role: 'bureau_officer', bureau: { $ne: rb.bureau } });
  if (!pgrc) pgrc = await User.create({ username: 'ps_pgrc', role: 'bureau_officer', bureau: 'PGRC', active: true, passwordHash: await User.hashPassword('local-password') });
  institution = await User.findOne({ username: 'inst_admin1' });
  institution.institutionPid = pid; await institution.save();
  const make = (n, bureau) => Case.create({ masterCaseId: `NX-2026-00900${n}`, reporterId: `RP-private-${n}`, institutionPid: pid, category: 'Fee Dispute', subCategory: 'Refund Denial', narrative: 'Private narrative', narrativeHash: `hash-${n}`, owningBureau: bureau, status: 'Under Process' });
  c1 = await make(1, rb.bureau); c2 = await make(2, pgrc.bureau);
});
it('[A-N82] owning bureaus confirm independently and replies reach only their own N70 items', async () => {
  const make = (c, u) => Query.create({ caseId: c._id, masterCaseId: c.masterCaseId, senderOfficerId: u._id, senderRole: u.role, senderBureau: u.bureau, recipientType: 'institution', queryText: 'Provide the fee notification' });
  const q1 = await make(c1, rb), q2 = await make(c2, pgrc);
  let r = await combined.propose(rb, { institutionPid: pid, queryIds: [q1.id, q2.id], coverNote: 'Please reply to each office item.' });
  const i1 = r.items.find(i => i.caseId === c1.masterCaseId), i2 = r.items.find(i => i.caseId === c2.masterCaseId);
  await expect(combined.decide(rb, r.id, i2.id, 'CONFIRMED')).rejects.toMatchObject({ status: 403 });
  await expect(combined.issue(rb, r.id)).rejects.toMatchObject({ status: 409 });
  await combined.decide(rb, r.id, i1.id, 'CONFIRMED');
  await combined.decide(pgrc, r.id, i2.id, 'WITHDRAWN');
  await combined.decide(pgrc, r.id, i2.id, 'CONFIRMED');
  r = await combined.issue(rb, r.id);
  expect(r.items.every(i => i.replyBy === null)).toBe(true);
  await combined.reply(institution, r.id, i1.id, { responseText: 'Notification attached separately.' });
  expect((await Query.findById(q1.id)).status).toBe('RESPONDED');
  expect((await Query.findById(q2.id)).status).toBe('PENDING');
  expect((await Case.findById(c1.id)).status).toBe('Under Process');
  expect(JSON.stringify(await combined.list(institution, pid))).not.toMatch(/RP-private|Private narrative|senderOfficerId|internalNotes/);
  for (const action of ['proposed', 'confirmed', 'withdrawn', 'issued', 'replied']) expect(await AuditEvent.exists({ action: `combined.${action}` })).toBeTruthy();
});
it('[A-N83] versions retain hashes and access requires a live case-specific officer grant', async () => {
  const payload = { documentType: 'Fee notification', name: 'fees.pdf', mimeType: 'application/pdf', content: Buffer.from('%PDF-1.4\nFee notification\n%%EOF').toString('base64') };
  const v1 = await locker.upload(institution, payload);
  const v2 = await locker.upload(institution, { ...payload, content: Buffer.from('%PDF-1.4\nRevised fee notification\n%%EOF').toString('base64') });
  expect(v2.version).toBe(2); expect(v1.hash).not.toBe(v2.hash);
  expect((await locker.LockerVersion.findById(v1.id)).hash).toBe(v1.hash);
  await expect(locker.download(rb, v1.id, c1.id)).rejects.toMatchObject({ status: 403 });
  const g = await locker.requestAccess(rb, { versionId: v1.id, caseId: c1.id });
  await locker.decide(institution, g.id, { expiresAt: new Date(Date.now() + 3600000).toISOString() });
  expect((await locker.download(rb, v1.id, c1.id)).isOriginal).toBe(false);
  await expect(locker.download(pgrc, v1.id, c2.id)).rejects.toMatchObject({ status: 403 });
  await locker.LockerGrant.updateOne({ _id: g.id }, { $set: { expiresAt: new Date(Date.now() - 1) } });
  await expect(locker.download(rb, v1.id, c1.id)).rejects.toMatchObject({ status: 403 });
  await locker.decide(institution, g.id, { revoke: true });
  expect((await locker.LockerGrant.findById(g.id)).state).toBe('REVOKED');
});
