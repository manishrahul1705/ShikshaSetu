/**
 * N66: Export footer helper.
 *
 * Appends or formats the mandatory SYNTHETIC DATA footer line for all exports.
 * Rule: Every export in the system must display that the data is synthetic.
 */

// Manish's explicit 25 Oct choice: no data-disclosure footer on exports.
// Preserve the exported symbol for existing callers; N55 attribution is separate.
export const SYNTHETIC_FOOTER_LINE = '';

/**
 * Returns the synthetic data footer line.
 * @param {Object} [meta={}] Optional metadata (e.g. exportDate, exportedByRole)
 * @returns {string}
 */
export function getExportFooter(meta = {}) {
  const parts = SYNTHETIC_FOOTER_LINE ? [SYNTHETIC_FOOTER_LINE] : [];
  if (meta.exportedByRole) {
    parts.push(`Generated by role: ${meta.exportedByRole}`);
  }
  if (meta.exportDate) {
    parts.push(`Date: ${meta.exportDate}`);
  }
  return parts.join(' | ');
}

export default getExportFooter;
